import type { Metadata } from "next"

export const siteName = "Migios"
export const siteTitle = "Migios · Software manajemen gym dan fitness"
export const siteDescription = (trialDays: number | null) =>
  `Kelola membership, kasir, jadwal kelas, sesi PT, absensi QR code dan wajah, sampai laporan keuangan gym dari satu aplikasi.${trialDays ? ` Coba gratis ${trialDays} hari.` : ""}`

export const siteUrl = (
  process.env.NEXT_PUBLIC_SITE_URL ?? "http://localhost:3000"
).replace(/\/$/, "")

// Backoffice base URL; the CTA buttons fall back to the on-page CTA section when it is not set.
const appUrl = process.env.NEXT_PUBLIC_APP_URL?.replace(/\/$/, "")
export const signUpHref = appUrl ? `${appUrl}/sign-up` : "#daftar"
export const signInHref = appUrl ? `${appUrl}/sign-in` : "#daftar"

// Contact channels for /kontak; each link stays hidden until its variable is set.
const contactWhatsapp = process.env.NEXT_PUBLIC_CONTACT_WHATSAPP?.replace(/\D/g, "")
const contactEmail = process.env.NEXT_PUBLIC_CONTACT_EMAIL?.trim()
export const whatsappHref = contactWhatsapp ? `https://wa.me/${contactWhatsapp}` : undefined
export const emailHref = contactEmail ? `mailto:${contactEmail}` : undefined

// The image generated by src/app/opengraph-image.tsx; only the home page picks it up on its own.
const shareImage = { url: "/opengraph-image", width: 1200, height: 630, alt: "Migios, software manajemen gym dan fitness" }

// Inner pages replace the root openGraph and twitter objects, so each page restates the shared fields.
export function pageMetadata({ path, title, description }: { path: string; title: string; description: string }) {
  return {
    title,
    description,
    alternates: { canonical: path },
    openGraph: {
      type: "website",
      locale: "id_ID",
      siteName,
      url: path,
      title: `${title} · ${siteName}`,
      description,
      images: [shareImage],
    },
    twitter: { card: "summary_large_image", title: `${title} · ${siteName}`, description, images: [shareImage] },
  } satisfies Metadata
}
